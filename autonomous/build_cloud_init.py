"""Builds the cloud-init for the autonomous x86-64 S-8 server.

  build_cloud_init.py <collector public key, base64> <lab commit SHA> <SSH public key>

The embedded run.sh, serve.py, endpoint.sh and scripts/check_evidence.sh are
read from the given lab commit itself (git objects, never the worktree),
after checking that the commit exists, so lab.txt names exactly the code
that runs. The output carries only PUBLIC keys (the collector's Ed25519
key and the owner's SSH key); it contains no token, password or private key.

Phase 1 (stock boot, no reboot, no boot setting): provider firewalls (ufw,
firewalld) are switched off at the very start of boot (bootcmd) so they can
never hide the server; nftables admits 22 (SSH, key only, no password),
80/443 (Caddy, Let's Encrypt for <ip>.sslip.io) and ICMP; the result
endpoint answers only requests signed with the collector's private key
(plus an unauthenticated /health with the current phase). run.sh starts
once cloud-init has finished and performs the phase-1 checks before the
runtime-only phase 2. Recovery: Vultr "View Console" (root password shown
in the Vultr panel) or SSH with the owner's key; a reboot undoes phase 2.
"""
import base64
import os
import re
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))


def git(*args):
    return subprocess.run(["git", "-C", here, *args], check=True, capture_output=True).stdout


def b64(lab_sha, path):
    # The file as stored in the lab commit, not as found in the worktree.
    return base64.b64encode(git("show", f"{lab_sha}:{path}")).decode()


SSH_KEY = re.compile(r"(ssh-ed25519|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384|sk-ssh-ed25519@openssh.com|ssh-rsa) [A-Za-z0-9+/]+={0,3}( [A-Za-z0-9@._+-]{1,64})?")


def build(pubkey, lab_sha, ssh_pubkey):
    ssh_pubkey = ssh_pubkey.strip()
    if not SSH_KEY.fullmatch(ssh_pubkey):
        raise SystemExit("SSH key must be ONE OpenSSH public key line (e.g. 'ssh-ed25519 AAAA... comment'), never a private key")
    if len(base64.b64decode(pubkey, validate=True)) != 32:
        raise SystemExit("public key must be 32 bytes (Ed25519), base64")
    if not re.fullmatch(r"[0-9a-f]{40}", lab_sha):
        raise SystemExit("lab commit must be a 40-hex SHA")
    try:
        if git("rev-parse", "--verify", "--quiet", f"{lab_sha}^{{commit}}").decode().strip() != lab_sha:
            raise SystemExit(f"{lab_sha} is not a commit of this repository")
    except subprocess.CalledProcessError:
        raise SystemExit(f"{lab_sha} is not a commit of this repository")
    files = {
        "/opt/sila-s8/run.sh": ("0755", b64(lab_sha, "autonomous/run.sh")),
        "/opt/sila-s8/serve.py": ("0755", b64(lab_sha, "autonomous/serve.py")),
        "/opt/sila-s8/check_evidence.sh": ("0755", b64(lab_sha, "scripts/check_evidence.sh")),
        "/opt/sila-s8/endpoint.sh": ("0755", b64(lab_sha, "autonomous/endpoint.sh")),
    }
    out = [
        "#cloud-config",
        "# SPDX-License-Identifier: Apache-2.0",
        "# Copyright 2026 Ahmed Ibrahim",
        "# SILA S-8 autonomous x86-64 measurement (generated by autonomous/build_cloud_init.py).",
        "# Contains no token, password or private key (public keys only).",
        "bootcmd:",
        "  # Before anything else on every boot: provider firewalls off, so they can",
        "  # never drop SSH/80/443. nftables (below) is the only firewall.",
        "  - [sh, -c, 'ufw --force disable >/dev/null 2>&1; systemctl disable --now ufw.service firewalld.service >/dev/null 2>&1; true']",
        "disable_root: false",
        "ssh_pwauth: false",
        "ssh_authorized_keys:",
        f"  - {ssh_pubkey}",
        "package_update: true",
        "packages: [openssh-server, git, curl, ca-certificates, util-linux, caddy, python3-cryptography, nftables]",
        "write_files:",
        "  - path: /opt/sila-s8/collector.pub",
        "    permissions: \"0644\"",
        f"    content: {pubkey}",
        "  - path: /opt/sila-s8/lab.txt",
        "    permissions: \"0644\"",
        f"    content: \"lab commit: {lab_sha}\"",
    ]
    for path, (mode, data) in files.items():
        out += [f"  - path: {path}", f"    permissions: \"{mode}\"", "    encoding: b64", f"    content: {data}"]
    out += [
        "  - path: /etc/ssh/sshd_config.d/00-sila-s8.conf",
        "    content: |",
        "      # 00-: read first; sshd keeps the first value of each setting.",
        "      PasswordAuthentication no",
        "      KbdInteractiveAuthentication no",
        "      PermitRootLogin prohibit-password",
        "  - path: /etc/nftables.conf",
        "    content: |",
        "      flush ruleset",
        "      table inet filter {",
        "        chain input {",
        "          type filter hook input priority 0; policy drop;",
        "          iif lo accept",
        "          ct state established,related accept",
        "          ip protocol icmp accept",
        "          meta l4proto ipv6-icmp accept",
        "          udp dport { 68, 546 } accept",
        "          tcp dport { 22, 80, 443 } accept",
        "        }",
        "      }",
        "  - path: /etc/systemd/system/sila-s8.slice",
        "    content: |",
        "      [Unit]",
        "      Description=SILA S-8 measurement (kept out of the confined system/user slices)",
        "  - path: /etc/systemd/system/sila-s8-measure.service",
        "    content: |",
        "      [Unit]",
        "      Description=SILA S-8 autonomous measurement (phase 1 checks, phase 2, measurement; resumable)",
        "      After=cloud-final.service network-online.target",
        "      Wants=network-online.target",
        "      [Service]",
        "      Type=oneshot",
        "      Slice=sila-s8.slice",
        "      ExecStart=/bin/bash /opt/sila-s8/run.sh",
        "      # Hard bound: run.sh limits each step (measurement 5 h); this stops",
        "      # anything else that hangs. Deletion is enforced by the billing guard.",
        "      TimeoutStartSec=6h",
        "      [Install]",
        "      WantedBy=multi-user.target",
        "  - path: /etc/systemd/system/sila-s8-serve.service",
        "    content: |",
        "      [Unit]",
        "      Description=SILA S-8 signed read-only result endpoint (localhost, behind Caddy)",
        "      After=network-online.target",
        "      [Service]",
        "      ExecStart=/usr/bin/python3 -I /opt/sila-s8/serve.py",
        "      DynamicUser=yes",
        "      NoNewPrivileges=yes",
        "      ProtectSystem=strict",
        "      ProtectHome=yes",
        "      PrivateTmp=yes",
        "      ReadOnlyPaths=/var/lib/sila-s8 /opt/sila-s8",
        "      Restart=always",
        "      [Install]",
        "      WantedBy=multi-user.target",
        "runcmd:",
        "  - mkdir -p /var/lib/sila-s8/out",
        "  - systemctl disable --now unattended-upgrades.service apt-daily.timer apt-daily-upgrade.timer snapd.service snapd.socket || true",
        "  - systemctl enable --now nftables.service",
        "  - systemctl enable ssh.service && (systemctl restart ssh.service || systemctl restart ssh.socket)",
        "  - systemctl daemon-reload",
        "  - systemctl enable --now sila-s8-serve.service",
        "  - bash /opt/sila-s8/endpoint.sh",
        "  # Starts when cloud-init has finished (After=cloud-final); no reboot.",
        "  - systemctl enable sila-s8-measure.service",
        "  - systemctl start --no-block sila-s8-measure.service",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    sys.stdout.write(build(sys.argv[1], sys.argv[2], sys.argv[3]))
