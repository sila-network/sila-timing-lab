"""Builds the cloud-init for the autonomous x86-64 S-8 server.

  build_cloud_init.py <collector public key, base64> <lab commit SHA>

The embedded run.sh, serve.py, endpoint.sh and scripts/check_evidence.sh are
read from the given lab commit itself (git objects, never the worktree),
after checking that the commit exists, so lab.txt names exactly the code
that runs. The output also carries the collector's Ed25519 PUBLIC key. It contains no token, password or private key. The server
needs no login: SSH is turned off, the firewall admits only 80/443 (Caddy,
Let's Encrypt for <ip>.sslip.io), and the result endpoint answers only
requests signed with the collector's private key.
"""
import base64
import os
import re
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))


def git(*args):
    return subprocess.run(["git", "-C", here, *args], check=True, capture_output=True).stdout


def b64(lab_sha, path):
    # The file as stored in the lab commit, not as found in the worktree.
    return base64.b64encode(git("show", f"{lab_sha}:{path}")).decode()


def build(pubkey, lab_sha):
    if len(base64.b64decode(pubkey, validate=True)) != 32:
        raise SystemExit("public key must be 32 bytes (Ed25519), base64")
    if not re.fullmatch(r"[0-9a-f]{40}", lab_sha):
        raise SystemExit("lab commit must be a 40-hex SHA")
    try:
        if git("rev-parse", "--verify", "--quiet", f"{lab_sha}^{{commit}}").decode().strip() != lab_sha:
            raise SystemExit(f"{lab_sha} is not a commit of this repository")
    except subprocess.CalledProcessError:
        raise SystemExit(f"{lab_sha} is not a commit of this repository")
    files = {
        "/opt/sila-s8/run.sh": ("0755", b64(lab_sha, "autonomous/run.sh")),
        "/opt/sila-s8/serve.py": ("0755", b64(lab_sha, "autonomous/serve.py")),
        "/opt/sila-s8/check_evidence.sh": ("0755", b64(lab_sha, "scripts/check_evidence.sh")),
        "/opt/sila-s8/endpoint.sh": ("0755", b64(lab_sha, "autonomous/endpoint.sh")),
    }
    out = [
        "#cloud-config",
        "# SPDX-License-Identifier: Apache-2.0",
        "# Copyright 2026 Ahmed Ibrahim",
        "# SILA S-8 autonomous x86-64 measurement (generated by autonomous/build_cloud_init.py).",
        "# Contains no token, password or private key.",
        "package_update: true",
        "packages: [git, curl, ca-certificates, util-linux, caddy, python3-cryptography, nftables]",
        "write_files:",
        "  - path: /etc/default/grub.d/99-sila-s8.cfg",
        "    content: |",
        '      GRUB_CMDLINE_LINUX_DEFAULT="$GRUB_CMDLINE_LINUX_DEFAULT isolcpus=2 nohz_full=2 rcu_nocbs=2 nosmt"',
        "  - path: /opt/sila-s8/collector.pub",
        "    permissions: \"0644\"",
        f"    content: {pubkey}",
        "  - path: /opt/sila-s8/lab.txt",
        "    permissions: \"0644\"",
        f"    content: \"lab commit: {lab_sha}\"",
    ]
    for path, (mode, data) in files.items():
        out += [f"  - path: {path}", f"    permissions: \"{mode}\"", "    encoding: b64", f"    content: {data}"]
    out += [
        "  - path: /etc/nftables.conf",
        "    content: |",
        "      flush ruleset",
        "      table inet filter {",
        "        chain input {",
        "          type filter hook input priority 0; policy drop;",
        "          iif lo accept",
        "          ct state established,related accept",
        "          ip protocol icmp accept",
        "          meta l4proto ipv6-icmp accept",
        "          udp dport { 68, 546 } accept",
        "          tcp dport { 80, 443 } accept",
        "        }",
        "      }",
        "  - path: /etc/systemd/system/sila-s8-measure.service",
        "    content: |",
        "      [Unit]",
        "      Description=SILA S-8 autonomous measurement (runs once)",
        "      After=network-online.target",
        "      Wants=network-online.target",
        "      ConditionPathExists=!/var/lib/sila-s8/started",
        "      ConditionKernelCommandLine=isolcpus=2",
        "      [Service]",
        "      Type=oneshot",
        "      ExecStart=/bin/bash /opt/sila-s8/run.sh",
        "      # Hard bound: run.sh limits each step (measurement 5 h); this stops",
        "      # anything else that hangs. Deletion is enforced by the operator.",
        "      TimeoutStartSec=6h",
        "      [Install]",
        "      WantedBy=multi-user.target",
        "  - path: /etc/systemd/system/sila-s8-serve.service",
        "    content: |",
        "      [Unit]",
        "      Description=SILA S-8 signed read-only result endpoint (localhost, behind Caddy)",
        "      After=network-online.target",
        "      [Service]",
        "      ExecStart=/usr/bin/python3 -I /opt/sila-s8/serve.py",
        "      DynamicUser=yes",
        "      NoNewPrivileges=yes",
        "      ProtectSystem=strict",
        "      ProtectHome=yes",
        "      PrivateTmp=yes",
        "      ReadOnlyPaths=/var/lib/sila-s8 /opt/sila-s8",
        "      Restart=always",
        "      [Install]",
        "      WantedBy=multi-user.target",
        "runcmd:",
        "  - mkdir -p /var/lib/sila-s8/out",
        "  - systemctl disable --now ssh.service ssh.socket unattended-upgrades.service apt-daily.timer apt-daily-upgrade.timer snapd.service snapd.socket || true",
        "  - systemctl enable --now nftables.service",
        "  - bash /opt/sila-s8/endpoint.sh",
        "  - systemctl enable sila-s8-serve.service sila-s8-measure.service",
        "  - update-grub",
        "  - reboot",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    sys.stdout.write(build(sys.argv[1], sys.argv[2]))
